import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const clientRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(clientRoot, '..');
const heroDir = path.join(clientRoot, 'node_modules/@heroicons/vue/24/outline');

function componentNameToIconId(name) {
  return name
    .replace(/Icon$/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
}

const files = fs.readdirSync(heroDir).filter((file) => file.endsWith('Icon.js')).sort();
const entries = files.map((file) => {
  const componentName = file.replace(/\.js$/, '');
  const key = componentNameToIconId(componentName);
  const src = fs.readFileSync(path.join(heroDir, file), 'utf8');
  const paths = [...src.matchAll(/d:\s*"([^"]+)"/g)].map((match) => match[1]);
  return { key, componentName, paths };
});

const ids = entries.map((entry) => entry.key);
const componentMap = Object.fromEntries(entries.map((entry) => [entry.key, entry.componentName]));
const pathMap = Object.fromEntries(entries.filter((entry) => entry.paths.length).map((entry) => [entry.key, entry.paths]));

const clientTs = `/* eslint-disable */
// Auto-generated by client/scripts/generate-heroicon-catalog.mjs — do not edit.

export const HEROICON_IDS = ${JSON.stringify(ids, null, 2)} as const;

export type HeroiconId = (typeof HEROICON_IDS)[number];

export const HEROICON_ID_SET = new Set<string>(HEROICON_IDS);

export const HEROICON_COMPONENT_MAP: Record<string, string> = ${JSON.stringify(componentMap, null, 2)};

export const DEFAULT_HERO_ICON_COLOR = '#111827';

export const HERO_ICON_COLOR_PRESETS = [
  '#111827',
  '#2563eb',
  '#7c3aed',
  '#db2777',
  '#dc2626',
  '#ea580c',
  '#ca8a04',
  '#16a34a',
  '#0891b2',
  '#4b5563',
] as const;
`;

const serverJs = `'use strict';

// Auto-generated by client/scripts/generate-heroicon-catalog.mjs — do not edit.

const HEROICON_IDS = ${JSON.stringify(ids, null, 2)};

const HEROICON_ID_SET = new Set(HEROICON_IDS);

const HEROICON_COMPONENT_MAP = ${JSON.stringify(componentMap, null, 2)};

const DEFAULT_HERO_ICON_COLOR = '#111827';

const HERO_ICON_COLOR_PRESET_SET = new Set([
  '#111827', '#2563eb', '#7c3aed', '#db2777', '#dc2626', '#ea580c', '#ca8a04', '#16a34a', '#0891b2', '#4b5563',
]);

function normalizeHeroIconKey(value) {
  const key = String(value || '').trim().toLowerCase();
  if (!key) return '';
  return HEROICON_ID_SET.has(key) ? key : '';
}

function normalizeHeroIconColor(value) {
  const raw = String(value || '').trim();
  if (!raw) return '';
  if (/^#[0-9a-f]{6}$/i.test(raw)) return raw.toLowerCase();
  if (/^#[0-9a-f]{3}$/i.test(raw)) {
    const hex = raw.slice(1);
    return ('#' + hex.split('').map((ch) => ch + ch).join('')).toLowerCase();
  }
  return '';
}

function resolveHeroIcon(key) {
  const normalized = normalizeHeroIconKey(key);
  if (!normalized) return null;
  return { key: normalized };
}

module.exports = {
  HEROICON_IDS,
  HEROICON_ID_SET,
  HEROICON_COMPONENT_MAP,
  DEFAULT_HERO_ICON_COLOR,
  HERO_ICON_COLOR_PRESET_SET,
  normalizeHeroIconKey,
  normalizeHeroIconColor,
  resolveHeroIcon,
};
`;

const embedJs = `;(function (root) {
  'use strict';
  var HEROICON_PATHS = ${JSON.stringify(pathMap, null, 2)};
  root.LiteDeskHeadlessHeroiconPaths = HEROICON_PATHS;
  root.ArivuHeadlessHeroiconPaths = HEROICON_PATHS;
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.mkdirSync(path.join(clientRoot, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(clientRoot, 'src/generated/heroiconCatalog.ts'), clientTs);
fs.writeFileSync(path.join(repoRoot, 'server/constants/heroiconCatalog.generated.js'), serverJs);
fs.writeFileSync(path.join(clientRoot, 'public/embed/headless-heroicon-paths.js'), embedJs);

console.log(`Generated ${ids.length} heroicons.`);
